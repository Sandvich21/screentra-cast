async fn fetch_nwt_events(
    client: &reqwest::Client,
    query: &TrafficQuery,
) -> Result<Vec<Value>, String> {
    let path_response = client
        .get("https://drivenwt.ca/Home/GetJsonDataPath?installationIndex=0")
        .send()
        .await
        .map_err(|e| format!("DriveNWT data path unavailable: {e}"))?;
    let path_body: Value = read_traffic_response_json(path_response, "Invalid DriveNWT data path response").await?;
    let path = path_body
        .get("filePath")
        .and_then(Value::as_str)
        .ok_or_else(|| "DriveNWT did not provide a data path".to_string())?;
    let path = path.replace("/../", "/");
    let data_response = client
        .get(format!("https://drivenwt.ca{path}"))
        .send()
        .await
        .map_err(|e| format!("DriveNWT data feed unavailable: {e}"))?;
    let data: Value = read_traffic_response_json(data_response, "Invalid DriveNWT data response").await?;
    let encoded = data
        .get("CoordsEncoded")
        .and_then(Value::as_str)
        .ok_or_else(|| "DriveNWT data has no encoded coordinates".to_string())?;
    let points = decode_nwt_coordinates(encoded)?;
    let mut point_index = 0usize;
    let mut events = Vec::new();
    for issue in data
        .get("Issues")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default()
    {
        let mut issue_points = Vec::new();
        for geometry in issue
            .get("Geometry")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default()
        {
            let count = geometry
                .get("NumPoints")
                .and_then(Value::as_u64)
                .unwrap_or(0) as usize;
            let end = point_index.saturating_add(count);
            if end > points.len() {
                return Err("DriveNWT encoded geometry is truncated".to_string());
            }
            issue_points.extend_from_slice(&points[point_index..end]);
            point_index = end;
        }
        if issue_points.is_empty()
            || issue.get("IsActiveInNextXDays").and_then(Value::as_bool) == Some(false)
        {
            continue;
        }
        let Some((event_lat, event_lon, distance_miles)) = issue_points
            .iter()
            .map(|&(lat, lon)| {
                (
                    lat,
                    lon,
                    traffic_distance_miles(query.lat, query.lon, lat, lon),
                )
            })
            .min_by(|a, b| a.2.partial_cmp(&b.2).unwrap_or(std::cmp::Ordering::Equal))
        else {
            continue;
        };
        if distance_miles > query.radius_miles {
            continue;
        }
        let description_obj = issue.get("Description");
        let description =
            saskatchewan_value_string(description_obj.and_then(|v| v.get("BaseDescription")));
        let location = saskatchewan_value_string(
            description_obj.and_then(|v| v.get("BaseLocationDescription")),
        );
        let road = issue
            .get("Geometry")
            .and_then(Value::as_array)
            .and_then(|geometry| geometry.first())
            .and_then(|geometry| geometry.get("MarkerInfo"))
            .map(|marker| saskatchewan_value_string(marker.get("LocationName")))
            .filter(|value| !value.is_empty())
            .unwrap_or(location.clone());
        let event_type = issue
            .get("TableViewInfo")
            .and_then(|v| v.get("IssueTypeId"))
            .map(|value| saskatchewan_value_string(Some(value)))
            .unwrap_or_else(|| "Road event".to_string());
        let category = traffic_event_category(&json!({
            "EventType": event_type,
            "Description": description,
            "LaneStatus": "",
            "IsFullClosure": false
        }));
        let last_update = description_obj
            .and_then(|v| v.get("UpdateTimeUtcEpochMillis"))
            .and_then(Value::as_i64)
            .and_then(DateTime::<Utc>::from_timestamp_millis)
            .map(|value| value.to_rfc3339())
            .unwrap_or_default();
        events.push(json!({
            "id": saskatchewan_value_string(issue.get("IssueId")),
            "category": category,
            "event_type": event_type,
            "road": road,
            "direction": "",
            "description": if description.is_empty() { location } else { description },
            "lane_status": "",
            "county": "",
            "distance_miles": (distance_miles * 10.0).round() / 10.0,
            "latitude": event_lat,
            "longitude": event_lon,
            "last_update": last_update,
            "detour": ""
        }));
    }
    events.sort_by(|a, b| {
        a.get("distance_miles")
            .and_then(Value::as_f64)
            .partial_cmp(&b.get("distance_miles").and_then(Value::as_f64))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    Ok(events)
}

fn decode_nwt_coordinates(encoded: &str) -> Result<Vec<(f64, f64)>, String> {
    let bytes = encoded.as_bytes();
    let mut index = 0usize;
    let mut lat = 0i64;
    let mut lon = 0i64;
    let mut points = Vec::new();
    while index < bytes.len() {
        let delta_lat = decode_nwt_value(bytes, &mut index)?;
        let delta_lon = decode_nwt_value(bytes, &mut index)?;
        lat = lat
            .checked_add(delta_lat)
            .ok_or_else(|| "DriveNWT latitude overflow".to_string())?;
        lon = lon
            .checked_add(delta_lon)
            .ok_or_else(|| "DriveNWT longitude overflow".to_string())?;
        points.push((lat as f64 / 100_000.0, lon as f64 / 100_000.0));
    }
    Ok(points)
}

fn decode_nwt_value(bytes: &[u8], index: &mut usize) -> Result<i64, String> {
    let mut result = 0i64;
    let mut shift = 0u32;
    loop {
        let byte = *bytes
            .get(*index)
            .ok_or_else(|| "DriveNWT encoded coordinate is truncated".to_string())?;
        *index += 1;
        let value = i64::from(byte).saturating_sub(63);
        result |= (value & 0x1f) << shift;
        if value < 0x20 {
            break;
        }
        shift += 5;
        if shift > 60 {
            return Err("DriveNWT encoded coordinate is too large".to_string());
        }
    }
    Ok(if result & 1 != 0 {
        !(result >> 1)
    } else {
        result >> 1
    })
}

