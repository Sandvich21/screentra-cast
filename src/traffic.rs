const SASKATCHEWAN_511_BASE: &str = "https://prod-sk.ibi511.com";
const SASKATCHEWAN_511_LIST: &str = "https://prod-sk.ibi511.com/List/GetData/traffic";

async fn fetch_saskatchewan_events(
    client: &reqwest::Client,
    query: &TrafficQuery,
) -> Result<Vec<Value>, String> {
    let payload = json!({
        "draw": 1,
        "start": 0,
        "length": 1000,
        "search": {"value": "", "regex": false},
        "order": [{"column": 1, "dir": "asc"}],
        "columns": []
    });
    let list_response = client
        .post(SASKATCHEWAN_511_LIST)
        .json(&payload)
        .send()
        .await
        .map_err(|e| format!("Saskatchewan 511 traffic feed unavailable: {e}"))?;
    if !list_response.status().is_success() {
        return Err(format!(
            "Saskatchewan 511 traffic feed returned {}",
            list_response.status()
        ));
    }
    let list_body: Value = read_traffic_response_json(list_response, "Invalid Saskatchewan 511 traffic response").await?;
    let mut coordinates = HashMap::new();
    for layer in ["Incidents", "Closures", "Construction"] {
        let url = format!("{SASKATCHEWAN_511_BASE}/map/mapIcons/{layer}");
        let response = client
            .get(url)
            .send()
            .await
            .map_err(|e| format!("Saskatchewan 511 map feed unavailable: {e}"))?;
        if !response.status().is_success() {
            return Err(format!(
                "Saskatchewan 511 map feed returned {}",
                response.status()
            ));
        }
        let body = decode_saskatchewan_json(
            &read_traffic_response_bytes(response, "Invalid Saskatchewan 511 map response").await?,
        )?;
        if let Some(items) = body.get("item2").and_then(Value::as_array) {
            for item in items {
                let Some(id) = item.get("itemId").and_then(Value::as_str) else {
                    continue;
                };
                let Some(location) = item.get("location").and_then(Value::as_array) else {
                    continue;
                };
                let (Some(lat), Some(lon)) = (
                    location.first().and_then(Value::as_f64),
                    location.get(1).and_then(Value::as_f64),
                ) else {
                    continue;
                };
                if lat.is_finite() && lon.is_finite() {
                    coordinates.insert(format!("{layer}:{id}"), (lat, lon));
                }
            }
        }
    }
    let rows = list_body
        .get("data")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    Ok(normalize_saskatchewan_events(&rows, &coordinates, query))
}

fn decode_saskatchewan_json(bytes: &[u8]) -> Result<Value, String> {
    let decoded = if bytes.starts_with(&[0x1f, 0x8b]) {
        let decoder = GzDecoder::new(Cursor::new(bytes));
        let mut output = Vec::new();
        decoder
            .take((16 * 1024 * 1024 + 1) as u64)
            .read_to_end(&mut output)
            .map_err(|e| format!("Invalid Saskatchewan 511 gzip response: {e}"))?;
        if output.len() > 16 * 1024 * 1024 {
            return Err("Saskatchewan 511 gzip response exceeds decompressed size limit".to_string());
        }
        output
    } else {
        bytes.to_vec()
    };
    serde_json::from_slice(&decoded)
        .map_err(|e| format!("Invalid Saskatchewan 511 map JSON response: {e}"))
}

fn saskatchewan_value_string(value: Option<&Value>) -> String {
    value
        .and_then(|item| {
            item.as_str()
                .map(ToString::to_string)
                .or_else(|| Some(item.to_string()))
        })
        .unwrap_or_default()
        .trim_matches('"')
        .to_string()
}

fn normalize_saskatchewan_events(
    rows: &[Value],
    coordinates: &HashMap<String, (f64, f64)>,
    query: &TrafficQuery,
) -> Vec<Value> {
    let mut events = Vec::new();
    for row in rows {
        let layer = saskatchewan_value_string(row.get("layerName"));
        let id = saskatchewan_value_string(row.get("id").or_else(|| row.get("DT_RowId")));
        let Some(&(event_lat, event_lon)) = coordinates.get(&format!("{layer}:{id}")) else {
            continue;
        };
        let distance_miles = traffic_distance_miles(query.lat, query.lon, event_lat, event_lon);
        if distance_miles > query.radius_miles {
            continue;
        }
        let event_type = {
            let subtype = saskatchewan_value_string(row.get("eventSubType"));
            if subtype.is_empty() {
                layer.clone()
            } else {
                subtype
            }
        };
        let description =
            traffic_public_html_text(&saskatchewan_value_string(row.get("description")));
        let lane_status = saskatchewan_value_string(row.get("laneDescription"));
        let category = traffic_event_category(&json!({
            "EventType": event_type,
            "Description": description,
            "LaneStatus": lane_status,
            "IsFullClosure": row.get("isFullClosure")
        }));
        events.push(json!({
            "id": saskatchewan_value_string(row.get("sourceId").or_else(|| row.get("id"))),
            "category": category,
            "event_type": event_type,
            "road": saskatchewan_value_string(row.get("roadwayName")),
            "direction": saskatchewan_value_string(row.get("direction")),
            "description": description,
            "lane_status": lane_status,
            "county": "",
            "distance_miles": (distance_miles * 10.0).round() / 10.0,
            "latitude": event_lat,
            "longitude": event_lon,
            "last_update": saskatchewan_value_string(row.get("lastUpdated")),
            "detour": traffic_public_html_text(&saskatchewan_value_string(row.get("detourDescription")))
        }));
    }
    events.sort_by(|a, b| {
        a.get("distance_miles")
            .and_then(Value::as_f64)
            .partial_cmp(&b.get("distance_miles").and_then(Value::as_f64))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    events
}

