fn normalize_penndot_events(body: &Value, query: &TrafficQuery) -> Vec<Value> {
    let values = body
        .get("Values")
        .and_then(|v| v.as_array())
        .cloned()
        .unwrap_or_default();
    let mut events = Vec::new();
    for event in values {
        let Some((event_lat, event_lon)) = traffic_event_point(&event) else {
            continue;
        };
        let distance_miles = traffic_distance_miles(query.lat, query.lon, event_lat, event_lon);
        if distance_miles > query.radius_miles {
            continue;
        }
        let category = traffic_event_category(&event);
        let facility = event.get("Facility").and_then(|v| v.as_str()).unwrap_or("");
        let direction = event
            .get("Direction")
            .and_then(|v| v.as_str())
            .unwrap_or("");
        let description = event
            .get("Description")
            .and_then(|v| v.as_str())
            .unwrap_or("");
        let event_id = event
            .get("EventID")
            .map(|v| v.to_string())
            .unwrap_or_default();
        events.push(json!({
            "id": event_id.trim_matches('"'),
            "category": category,
            "event_type": event.get("EventType").and_then(|v| v.as_str()).unwrap_or("other"),
            "road": facility,
            "direction": direction,
            "description": description,
            "lane_status": event.get("LaneStatus").and_then(|v| v.as_str()).unwrap_or(""),
            "county": event.get("CountyName").and_then(|v| v.as_str()).unwrap_or(""),
            "distance_miles": (distance_miles * 10.0).round() / 10.0,
            "latitude": event_lat,
            "longitude": event_lon,
            "last_update": event.get("LastUpdate").and_then(|v| v.as_str()).unwrap_or(""),
            "detour": event.get("DetourInEffect").and_then(|v| v.as_str()).unwrap_or("")
        }));
    }
    events.sort_by(|a, b| {
        a.get("distance_miles")
            .and_then(|v| v.as_f64())
            .partial_cmp(&b.get("distance_miles").and_then(|v| v.as_f64()))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    events
}

