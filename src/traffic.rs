fn point_in_boundary(lat: f64, lon: f64, boundary: &[(f64, f64)]) -> bool {
    if !lat.is_finite() || !lon.is_finite() {
        return false;
    }
    let mut inside = false;
    let mut previous = *boundary.last().unwrap_or(&(0.0, 0.0));
    for &current in boundary {
        let (current_lat, current_lon) = current;
        let (previous_lat, previous_lon) = previous;
        let crosses = (current_lat > lat) != (previous_lat > lat)
            && lon
                < (previous_lon - current_lon) * (lat - current_lat) / (previous_lat - current_lat)
                    + current_lon;
        if crosses {
            inside = !inside;
        }
        previous = current;
    }
    inside
}

