fn normalize_open511_bc_events(body: &Value, query: &TrafficQuery) -> Vec<Value> {
    let events = body
        .get("events")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    let mut normalized = Vec::new();
    for event in events {
        let Some((event_lat, event_lon)) = event
            .get("geography")
            .and_then(|geography| geography.get("coordinates"))
            .and_then(first_geo_coordinate)
        else {
            continue;
        };
        let distance_miles = traffic_distance_miles(query.lat, query.lon, event_lat, event_lon);
        if distance_miles > query.radius_miles {
            continue;
        }
        let road = event
            .get("roads")
            .and_then(Value::as_array)
            .and_then(|roads| roads.first())
            .and_then(|road| road.get("name"))
            .and_then(Value::as_str)
            .unwrap_or("");
        let direction = event
            .get("roads")
            .and_then(Value::as_array)
            .and_then(|roads| roads.first())
            .and_then(|road| road.get("direction"))
            .and_then(Value::as_str)
            .unwrap_or("");
        let event_type = event
            .get("event_type")
            .and_then(Value::as_str)
            .unwrap_or("");
        let description = event
            .get("description")
            .and_then(Value::as_str)
            .unwrap_or("");
        let lane_status = event
            .get("roads")
            .and_then(Value::as_array)
            .and_then(|roads| roads.first())
            .and_then(|road| road.get("state"))
            .and_then(Value::as_str)
            .unwrap_or("");
        let category = traffic_event_category(&json!({
            "EventType": event_type,
            "Description": description,
            "LaneStatus": lane_status,
        }));
        let area = event
            .get("areas")
            .and_then(Value::as_array)
            .and_then(|areas| areas.first())
            .and_then(|area| area.get("name"))
            .and_then(Value::as_str)
            .unwrap_or("");
        normalized.push(json!({
            "id": event.get("id").and_then(Value::as_str).unwrap_or(""),
            "category": category,
            "event_type": event_type,
            "road": road,
            "direction": direction,
            "description": description,
            "lane_status": lane_status,
            "county": area,
            "distance_miles": (distance_miles * 10.0).round() / 10.0,
            "latitude": event_lat,
            "longitude": event_lon,
            "last_update": event.get("updated").and_then(Value::as_str).unwrap_or(""),
            "detour": ""
        }));
    }
    normalized.sort_by(|a, b| {
        a.get("distance_miles")
            .and_then(Value::as_f64)
            .partial_cmp(&b.get("distance_miles").and_then(Value::as_f64))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    normalized
}

async fn fetch_wzdx_events(
    client: &reqwest::Client,
    query: &TrafficQuery,
) -> Result<Vec<Value>, String> {
    let url = wzdx_feed_url(query)
        .ok_or_else(|| "No public WZDx feed is registered for this location".to_string())?;
    let upstream = client
        .get(url)
        .send()
        .await
        .map_err(|e| format!("WZDx traffic feed unavailable: {e}"))?;
    if !upstream.status().is_success() {
        return Err(format!("WZDx traffic feed returned {}", upstream.status()));
    }
    let mut body: Value = read_traffic_response_json(upstream, "Invalid WZDx traffic response").await?;
    // Some public feeds incorrectly advertise a JSON document as a JSON string.
    if let Some(encoded) = body.as_str() {
        body = serde_json::from_str(encoded)
            .map_err(|e| format!("Invalid encoded WZDx traffic response: {e}"))?;
    }
    Ok(normalize_wzdx_events(&body, query))
}

fn geo_number(value: &Value) -> Option<f64> {
    value
        .as_f64()
        .or_else(|| value.as_str().and_then(|text| text.parse::<f64>().ok()))
}

fn first_geo_coordinate(value: &Value) -> Option<(f64, f64)> {
    let values = value.as_array()?;
    if values.len() >= 2 {
        if let (Some(lon), Some(lat)) = (geo_number(&values[0]), geo_number(&values[1])) {
            if lon.is_finite() && lat.is_finite() {
                return Some((lat, lon));
            }
        }
    }
    values.iter().find_map(first_geo_coordinate)
}

fn wzdx_string(value: &Value, key: &str) -> String {
    value
        .get(key)
        .and_then(|item| item.as_str())
        .unwrap_or("")
        .to_string()
}

fn wzdx_first_road(value: &Value) -> String {
    value
        .get("road_names")
        .and_then(|item| item.as_array())
        .and_then(|items| items.iter().find_map(|item| item.as_str()))
        .unwrap_or("")
        .to_string()
}

fn wzdx_first_work_type(value: &Value) -> String {
    value
        .get("types_of_work")
        .and_then(|item| item.as_array())
        .and_then(|items| items.first())
        .and_then(|item| item.get("type_name"))
        .and_then(|item| item.as_str())
        .unwrap_or("")
        .to_string()
}

fn normalize_wzdx_events(body: &Value, query: &TrafficQuery) -> Vec<Value> {
    let features = body
        .get("features")
        .and_then(|value| value.as_array())
        .cloned()
        .unwrap_or_default();
    let mut events = Vec::new();
    for feature in features {
        let Some((event_lat, event_lon)) = feature
            .get("geometry")
            .and_then(|geometry| geometry.get("coordinates"))
            .and_then(first_geo_coordinate)
        else {
            continue;
        };
        let distance_miles = traffic_distance_miles(query.lat, query.lon, event_lat, event_lon);
        if distance_miles > query.radius_miles {
            continue;
        }
        let properties = feature.get("properties").unwrap_or(&feature);
        let core = properties.get("core_details").unwrap_or(properties);
        let event_type = wzdx_string(core, "event_type");
        let mut description = wzdx_string(core, "description");
        if description.is_empty() {
            description = wzdx_first_work_type(core);
        }
        let lane_status = wzdx_string(properties, "vehicle_impact").replace('-', " ");
        let category = traffic_event_category(&json!({
            "EventType": event_type,
            "Description": description,
            "LaneStatus": lane_status,
        }));
        let road = {
            let value = wzdx_first_road(core);
            if value.is_empty() {
                description.clone()
            } else {
                value
            }
        };
        let last_update = {
            let update = wzdx_string(core, "update_date");
            if update.is_empty() {
                wzdx_string(properties, "start_date")
            } else {
                update
            }
        };
        events.push(json!({
            "id": feature.get("id").and_then(|value| value.as_str()).unwrap_or(""),
            "category": category,
            "event_type": event_type,
            "road": road,
            "direction": wzdx_string(core, "direction"),
            "description": description,
            "lane_status": lane_status,
            "county": "",
            "distance_miles": (distance_miles * 10.0).round() / 10.0,
            "latitude": event_lat,
            "longitude": event_lon,
            "last_update": last_update,
            "detour": ""
        }));
    }
    events.sort_by(|a, b| {
        a.get("distance_miles")
            .and_then(|value| value.as_f64())
            .partial_cmp(&b.get("distance_miles").and_then(|value| value.as_f64()))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    events
}

