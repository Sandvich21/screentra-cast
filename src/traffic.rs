fn traffic_event_point(value: &Value) -> Option<(f64, f64)> {
    for key in ["IncidentLocLatLong", "FromLocLatLong", "ToLocLatLong"] {
        let raw = value.get(key).and_then(|v| v.as_str()).unwrap_or("");
        let mut parts = raw.split(',').map(str::trim);
        let lat = parts.next().and_then(|v| v.parse::<f64>().ok());
        let lon = parts.next().and_then(|v| v.parse::<f64>().ok());
        if let (Some(lat), Some(lon)) = (lat, lon) {
            if lat.is_finite()
                && lon.is_finite()
                && (-90.0..=90.0).contains(&lat)
                && (-180.0..=180.0).contains(&lon)
            {
                return Some((lat, lon));
            }
        }
    }
    None
}

fn traffic_distance_miles(a_lat: f64, a_lon: f64, b_lat: f64, b_lon: f64) -> f64 {
    let radius = 3958.7613_f64;
    let dlat = (b_lat - a_lat).to_radians();
    let dlon = (b_lon - a_lon).to_radians();
    let lat1 = a_lat.to_radians();
    let lat2 = b_lat.to_radians();
    let h = (dlat / 2.0).sin().powi(2) + lat1.cos() * lat2.cos() * (dlon / 2.0).sin().powi(2);
    2.0 * radius * h.sqrt().asin()
}

fn traffic_event_category(event: &Value) -> &'static str {
    let event_type = event
        .get("EventType")
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_lowercase();
    let description = event
        .get("Description")
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_lowercase();
    let lane_status = event
        .get("LaneStatus")
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_lowercase();
    let combined = format!("{} {} {}", event_type, description, lane_status);
    if ["crash", "accident", "collision", "rollover"]
        .iter()
        .any(|needle| combined.contains(needle))
    {
        "crash"
    } else if lane_status.contains("closed")
        || event_type.contains("closure")
        || combined.contains("all lanes closed")
    {
        "closure"
    } else if ["delay", "congestion", "slow traffic"]
        .iter()
        .any(|needle| combined.contains(needle))
        || lane_status.contains("restriction")
    {
        "delay"
    } else {
        "other"
    }
}

fn traffic_public_html_text(fragment: &str) -> String {
    let mut text = String::with_capacity(fragment.len());
    let mut in_tag = false;
    for ch in fragment.chars() {
        match ch {
            '<' => in_tag = true,
            '>' => {
                in_tag = false;
                text.push(' ');
            }
            _ if !in_tag => text.push(ch),
            _ => {}
        }
    }
    text.replace("&nbsp;", " ")
        .replace("&amp;", "&")
        .replace("&quot;", "\"")
        .replace("&#39;", "'")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

fn traffic_public_html_section<'a>(html: &'a str, class_name: &str) -> Option<&'a str> {
    let marker = format!("class=\"{class_name}\"");
    let start = html.find(&marker)? + marker.len();
    let start = html[start..].find('>')? + start + 1;
    let end = html[start..].find("</")? + start;
    Some(&html[start..end])
}

fn traffic_public_html_field(html: &str, label: &str) -> String {
    let strong_marker = format!("<strong>{label}</strong>");
    if let Some(marker_start) = html.find(&strong_marker) {
        let value_start = marker_start + strong_marker.len();
        if let Some(value_end_rel) = html[value_start..].find("</td>") {
            return traffic_public_html_text(&html[value_start..value_start + value_end_rel]);
        }
    }
    for header_start in html.match_indices("<th").map(|(index, _)| index) {
        let Some(header_end_rel) = html[header_start..].find("</th>") else {
            continue;
        };
        let header_end = header_start + header_end_rel + "</th>".len();
        if traffic_public_html_text(&html[header_start..header_end]).trim() != label {
            continue;
        }
        let Some(value_start_rel) = html[header_end..].find("<td") else {
            continue;
        };
        let value_start = header_end + value_start_rel;
        let Some(value_content_rel) = html[value_start..].find('>') else {
            continue;
        };
        let value_start = value_start + value_content_rel + 1;
        let Some(value_end_rel) = html[value_start..].find("</td>") else {
            continue;
        };
        return traffic_public_html_text(&html[value_start..value_start + value_end_rel]);
    }
    String::new()
}

async fn fetch_public_511_events(client: &reqwest::Client, query: &TrafficQuery) -> Vec<Value> {
    let layers: &[(&str, &str)] = &[
        ("MajorRouteIncident", "crash"),
        ("OtherRouteIncident", "incident"),
        ("MajorRouteClosure", "closure"),
        ("OtherRouteClosure", "closure"),
        ("ActiveRoadwork", "roadwork"),
        ("TurnpikeActiveRoadwork", "roadwork"),
        ("TurnpikeIncidents", "incident"),
        ("TurnpikeClosures", "closure"),
        ("SpecialEvents", "other"),
    ];
    let layer_requests = layers.iter().map(|(layer, kind)| async move {
        let url = format!("https://www.511pa.com/map/mapIcons/{layer}");
        let response = client.get(url).send().await.ok()?;
        let body: Value = read_traffic_response_json(response, "Pennsylvania 511 map response")
            .await
            .ok()?;
        let items = body.get("item2")?.as_array()?;
        Some(
            items
                .iter()
                .filter_map(|item| {
                    let location = item.get("location")?.as_array()?;
                    let event_lat = location.first()?.as_f64()?;
                    let event_lon = location.get(1)?.as_f64()?;
                    if !event_lat.is_finite() || !event_lon.is_finite() {
                        return None;
                    }
                    let distance_miles =
                        traffic_distance_miles(query.lat, query.lon, event_lat, event_lon);
                    if distance_miles > query.radius_miles {
                        return None;
                    }
                    Some(json!({
                        "layer": *layer,
                        "kind": *kind,
                        "id": item.get("itemId").and_then(|v| v.as_str()).unwrap_or(""),
                        "latitude": event_lat,
                        "longitude": event_lon,
                        "distance_miles": distance_miles,
                    }))
                })
                .collect::<Vec<_>>(),
        )
    });
    let mut nearby = Vec::new();
    for result in futures_util::future::join_all(layer_requests).await {
        if let Some(events) = result {
            nearby.extend(events);
        }
    }
    nearby.sort_by(|a, b| {
        a.get("distance_miles")
            .and_then(|v| v.as_f64())
            .partial_cmp(&b.get("distance_miles").and_then(|v| v.as_f64()))
            .unwrap_or(std::cmp::Ordering::Equal)
    });

    let tooltip_requests = nearby.into_iter().map(|event| async move {
        let layer = event.get("layer").and_then(|v| v.as_str()).unwrap_or("");
        let id = event.get("id").and_then(|v| v.as_str()).unwrap_or("");
        let url = format!("https://www.511pa.com/tooltip/{layer}/{id}?lang=en");
        let response = client.get(url).send().await.ok()?;
        let html = String::from_utf8(read_traffic_response_bytes(response, "Pennsylvania tooltip").await.ok()?).ok()?;
        let description = traffic_public_html_section(&html, "descSection")
            .map(traffic_public_html_text).unwrap_or_default();
        let title = html.find("<h4").and_then(|start| html[start..].find('>').map(|offset| start + offset + 1))
            .and_then(|start| html[start..].find("</h4>").map(|offset| traffic_public_html_text(&html[start..start + offset])))
            .unwrap_or_else(|| "Traffic event".to_string());
        let kind = event.get("kind").and_then(|v| v.as_str()).unwrap_or("other");
        let category = if description.to_lowercase().contains("crash") || description.to_lowercase().contains("accident") || description.to_lowercase().contains("collision") {
            "crash"
        } else {
            kind
        };
        Some(json!({
            "id": id,
            "category": category,
            "event_type": title,
            "road": traffic_public_html_field(&html, "Location"),
            "direction": "",
            "description": description,
            "lane_status": "",
            "county": "",
            "distance_miles": (event.get("distance_miles").and_then(|v| v.as_f64()).unwrap_or(0.0) * 10.0).round() / 10.0,
            "latitude": event.get("latitude").and_then(|v| v.as_f64()).unwrap_or(0.0),
            "longitude": event.get("longitude").and_then(|v| v.as_f64()).unwrap_or(0.0),
            "last_update": traffic_public_html_field(&html, "Last Updated"),
            "detour": ""
        }))
    });
    futures_util::future::join_all(tooltip_requests)
        .await
        .into_iter()
        .flatten()
        .collect()
}

async fn fetch_maryland_events(
    client: &reqwest::Client,
    query: &TrafficQuery,
) -> Result<Vec<Value>, String> {
    const URL: &str = "https://chart.maryland.gov/DataFeeds/GetIncidentJson";
    let upstream = client
        .get(URL)
        .send()
        .await
        .map_err(|e| format!("Maryland CHART traffic feed unavailable: {e}"))?;
    if !upstream.status().is_success() {
        return Err(format!(
            "Maryland CHART traffic feed returned {}",
            upstream.status()
        ));
    }
    let body: Value = read_traffic_response_json(upstream, "Invalid Maryland CHART traffic response").await?;
    Ok(normalize_maryland_events(&body, query))
}

fn normalize_maryland_events(body: &Value, query: &TrafficQuery) -> Vec<Value> {
    let values = body
        .as_array()
        .or_else(|| body.get("data").and_then(|value| value.as_array()))
        .cloned()
        .unwrap_or_default();
    let mut events = Vec::new();
    for event in values {
        let Some(event_lat) = event.get("lat").and_then(|value| value.as_f64()) else {
            continue;
        };
        let Some(event_lon) = event.get("lon").and_then(|value| value.as_f64()) else {
            continue;
        };
        if !event_lat.is_finite() || !event_lon.is_finite() {
            continue;
        }
        let distance_miles = traffic_distance_miles(query.lat, query.lon, event_lat, event_lon);
        if distance_miles > query.radius_miles {
            continue;
        }
        let event_type = event
            .get("incidentType")
            .and_then(|value| value.as_str())
            .unwrap_or("other");
        let description = event
            .get("description")
            .and_then(|value| value.as_str())
            .unwrap_or("");
        let lane_status = event
            .get("lanesStatus")
            .and_then(|value| value.as_str())
            .unwrap_or("");
        let category = traffic_event_category(&json!({
            "EventType": event_type,
            "Description": description,
            "LaneStatus": lane_status,
        }));
        let road = event
            .get("name")
            .and_then(|value| value.as_str())
            .filter(|value| !value.is_empty())
            .unwrap_or(description);
        events.push(json!({
            "id": event.get("id").and_then(|value| value.as_str()).unwrap_or(""),
            "category": category,
            "event_type": event_type,
            "road": road,
            "direction": event.get("direction").and_then(|value| value.as_str()).unwrap_or(""),
            "description": description,
            "lane_status": lane_status,
            "county": event.get("county").and_then(|value| value.as_str()).unwrap_or(""),
            "distance_miles": (distance_miles * 10.0).round() / 10.0,
            "latitude": event_lat,
            "longitude": event_lon,
            "last_update": maryland_timestamp(event.get("lastCachedDataUpdateTime")),
            "detour": ""
        }));
    }
    events.sort_by(|a, b| {
        a.get("distance_miles")
            .and_then(|value| value.as_f64())
            .partial_cmp(&b.get("distance_miles").and_then(|value| value.as_f64()))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    events
}

fn maryland_timestamp(value: Option<&Value>) -> String {
    value
        .and_then(|value| value.as_i64())
        .and_then(DateTime::<Utc>::from_timestamp_millis)
        .map(|timestamp| timestamp.to_rfc3339())
        .unwrap_or_default()
}

fn ny_string(event: &Value, keys: &[&str]) -> String {
    keys.iter()
        .find_map(|key| event.get(*key).and_then(|value| value.as_str()))
        .unwrap_or("")
        .to_string()
}

fn ny_number(event: &Value, keys: &[&str]) -> Option<f64> {
    keys.iter().find_map(|key| {
        let value = event.get(*key)?;
        value
            .as_f64()
            .or_else(|| value.as_str().and_then(|text| text.trim().parse().ok()))
    })
}

